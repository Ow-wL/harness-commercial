def barrier_level(info: dict, has_license: bool = False) -> tuple[str, list[str]]:
    """등급과 그 이유. 위에서부터 먼저 맞는 규칙을 쓴다."""
    reasons = []
    if info["인허가"] == "허가":
        reasons.append("허가업")
    if info["면허"] and not has_license:
        reasons.append(f"본인 {info['면허']} 면허 필요")
    if reasons:
        return "높음", reasons
    if info["인허가"] == "등록":
        reasons.append("등록업(시설기준 심사)")
    if info["입지규제"]:
        reasons.append("학교 주변 입지 규제")
    if reasons:
        return "중간", reasons
    if info["면허"] and has_license:
        return "낮음", [f"{info['면허']} 면허 보유로 해제"]
    return "낮음", [f"{info['인허가']}, 면허·입지 규제 없음"]


def access_tag(biz_code: str, user_licenses: Optional[Iterable[str]] = None) -> Optional[dict]:
    """
    업종의 초보자 접근성 태그. 표에 없는 업종은 None (모르면 모른다고 둔다).
    user_licenses: 사용자가 가진 면허 이름들. 업종 요구 면허 문자열에 포함되면 보유로 본다.
    """
    info = ACCESS.get(biz_code)
    if info is None:
        return None
    lic = [l.strip() for l in (user_licenses or []) if l and l.strip()]
    has = bool(info["면허"]) and any(l in info["면허"] or info["면허"] in l for l in lic)
    level, reasons = barrier_level(info, has)
    cost = info["비용_만원"]
    return {
        "제도_진입장벽": level,
        "이유": reasons,
        "인허가": info["인허가"],
        "근거": info["근거"],
        "필요_면허": info["면허"],
        "면허_보유": has if info["면허"] else None,
        "입지_규제": LOCATION_RULE if info["입지규제"] else None,
        "개업전_교육": info["교육"],
        "창업비용_참고": (
            {"값_만원": cost[0], "기준": f"대한상의 2023 프랜차이즈 실태조사 '{cost[1]}' 가맹점 평균",
             "비교": f"소상공인 전체 평균 {SME_AVG_COST:,}만원"}
            if cost else {"값_만원": None, "기준": "업종별 공식 통계 미확인",
                          "비교": f"소상공인 전체 평균 {SME_AVG_COST:,}만원"}),
        "점수_반영": False,
    }


