SCHOOL_CHECK_M = 300   # 학교 좌표는 중심점이라 실제 경계는 더 가깝다 → 200m 규정보다 넓게 본다


def school_check(lat: float, lng: float, facilities) -> Optional[dict]:
    """
    분석 지점 주변 초·중·고 수. 교육환경보호구역(경계 200m) 해당 '가능성'만 알린다.
    판정은 관할 교육지원청 몫이다 (학교 경계·출입문 위치 데이터가 없다).
    """
    import math
    if lat is None or lng is None or not facilities:
        return None
    near = []
    for f in facilities:
        if f.get("type") not in SCHOOL_TYPES:
            continue
        p1, p2 = math.radians(lat), math.radians(f["lat"])
        a = (math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2)
             * math.sin(math.radians(f["lng"] - lng) / 2) ** 2)
        d = 2 * 6371000 * math.asin(math.sqrt(a))
        if d <= SCHOOL_CHECK_M:
            near.append({"종류": f["type"], "이름": f.get("학교명"), "거리_m": round(d)})
    near.sort(key=lambda x: x["거리_m"])
    return {
        "기준": f"학교 중심점 {SCHOOL_CHECK_M}m 이내 (규정은 학교 경계 200m)",
        "학교수": len(near),
        "목록": near[:5],
        "판단": ("보호구역 해당 가능성 있음 — 관할 교육지원청에 확인 필요" if near
                 else "중심점 300m 안에 초·중·고 없음 (보호구역 가능성 낮음)"),
    }
