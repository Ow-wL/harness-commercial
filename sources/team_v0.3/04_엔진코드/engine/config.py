for _code, _words in SYNONYM.items():
    for _w in _words:
        _SYN_INDEX[_norm_text(_w)] = _code
for _code, _nm in CODE_NAME.items():
    _SYN_INDEX.setdefault(_norm_text(_nm), _code)


def resolve_biz(user_input: str):
    """
    사용자 입력("부평역 근처 피시방")을 소분류 코드로 변환한다.
    반환: (코드, 공식명) 또는 (None, None)
    """
    q = _norm_text(user_input)
    if q.upper() in CODE_NAME:                      # 코드를 직접 넣은 경우
        return q.upper(), CODE_NAME[q.upper()]
    if q in _SYN_INDEX:                             # 완전 일치
        code = _SYN_INDEX[q]
        return code, CODE_NAME.get(code)
    for key, code in sorted(_SYN_INDEX.items(), key=lambda x: -len(x[0])):
        if key and key in q:                        # 문장 안에 포함 (긴 것 우선)
            return code, CODE_NAME.get(code)
    return None, None


