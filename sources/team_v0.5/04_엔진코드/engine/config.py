# 11-1. 종사자 수(고객성 C3) 업종 민감도
#   v0.4까지는 29개 업종 모두 '종사자 많을수록 +'였다(학원·독서실·세탁소도 오피스가에서 점수 상승).
#   새 숫자를 만들지 않고 시장성의 직장형/주거형 선호(WORK_PREF, -1~+1)를 그대로 재사용한다.
#     민감도 = 0.5 + 0.5 × WORK_PREF   (주거형 -0.8 → 0.1, 중립 0 → 0.5, 직장형 +0.7 → 0.85)
#   C4와 같은 방식으로 p3 = 50 + (백분위 - 50) × 민감도
def worker_sens(code: str) -> float:
    return 0.5 + 0.5 * WORK_PREF.get(code, DEFAULT_WORK_PREF)


